# --------------------------------------------------------------------------------------------- helpers
def normalize_locale(value: Optional[str]) -> Optional[str]:
    """'en-GB' -> 'en', 'DE' -> 'de'; unsupported -> None."""
    if not value:
        return None
    base = str(value).strip().replace("_", "-").split("-")[0].lower()
    return base if base in SUPPORTED_LOCALES else None


def t(key: str, locale: Optional[str] = None, **kwargs: Any) -> str:
    loc = normalize_locale(locale) or DEFAULT_LOCALE
    text = CATALOG.get(loc, {}).get(key) or CATALOG[DEFAULT_LOCALE].get(key) or key
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            pass
    return text


def catalog(locale: Optional[str] = None) -> dict[str, str]:
    """Full merged catalog for a locale (English fallback filled in) — e.g. for booking.js."""
    loc = normalize_locale(locale) or DEFAULT_LOCALE
    merged = dict(CATALOG[DEFAULT_LOCALE])
    merged.update(CATALOG.get(loc, {}))
    return merged


def parse_accept_language(header: Optional[str]) -> Optional[str]:
    """Best supported language from an Accept-Language header, honouring q-values."""
    if not header:
        return None
    choices = []
    for i, part in enumerate(header.split(",")):
        bits = part.strip().split(";")
        tag = bits[0].strip()
        q = 1.0
        for b in bits[1:]:
            b = b.strip()
            if b.startswith("q="):
                try:
                    q = float(b[2:])
                except ValueError:
                    q = 0.0
        loc = normalize_locale(tag)
        if loc and q > 0:
            choices.append((-q, i, loc))
    return sorted(choices)[0][2] if choices else None


def get_locale(request, host_locale: Optional[str] = None) -> str:
    """Resolve the invitee-facing locale (see module docstring) and cache it on request.state."""
    loc = None
    if request is not None:
        loc = normalize_locale(request.query_params.get("lang")) or normalize_locale(request.cookies.get(LANG_COOKIE))
    if not loc:
        host = normalize_locale(host_locale)
        if host and host != DEFAULT_LOCALE:
            loc = host
    if not loc and request is not None:
        loc = parse_accept_language(request.headers.get("accept-language"))
    loc = loc or DEFAULT_LOCALE
    if request is not None:
        try:
            request.state.locale = loc
        except Exception:  # pragma: no cover
            pass
    return loc


@pass_context
def jinja_t(context, key: str, locale: Optional[str] = None, **kwargs: Any) -> str:
    """Jinja global `t(key, [locale], **fmt)`; defaults to the template's `locale` variable."""
    if not locale:
        locale = context.get("locale")
        if not locale:
            req = context.get("request")
            locale = getattr(getattr(req, "state", None), "locale", None) if req is not None else None
    return t(key, locale, **kwargs)


_EN_DATE_FORMATS = {"full": "%A %d %B %Y", "day_month": "%A %d %B", "month_year": "%B %Y"}


def format_date(value, locale: Optional[str] = None, style: str = "full", en_fmt: Optional[str] = None) -> str:
    """Localized date (date or datetime). style: full | day_month | month_year.
    English keeps the exact strftime output (`en_fmt`, else the style's default format)."""
    loc = normalize_locale(locale) or DEFAULT_LOCALE
    if loc == DEFAULT_LOCALE:
        return value.strftime(en_fmt or _EN_DATE_FORMATS.get(style, _EN_DATE_FORMATS["full"]))
    weekdays = t("date.weekdays", loc).split(",")
    months = t("date.months", loc).split(",")
    return t(f"date.{style}", loc, weekday=weekdays[value.weekday()], day=value.day, dd=f"{value.day:02d}",
             month=months[value.month - 1], year=value.year)


def status_label(status: Optional[str], locale: Optional[str] = None) -> str:
    """Invitee-facing booking status label ('Pending confirmation', 'Confirmed', ...)."""
    status = status or ""
    if status == "pending":
        return t("confirm.pending", locale)
    key = f"status.{status}"
    if key in CATALOG[DEFAULT_LOCALE]:
        return t(key, locale)
    return status.replace("_", " ").capitalize()


@pass_context
def jinja_ldt(context, value, tz: str = "UTC") -> str:
    """Locale-aware version of the `dt` filter ('Mon 18 Nov 2026, 14:00 GMT' in English)."""
    loc = normalize_locale(context.get("locale")) or DEFAULT_LOCALE
    if loc == DEFAULT_LOCALE or not value:
        return context.environment.filters["dt"](value, tz)
    import datetime as _dt

    from app.services import timeutil as tu

    if isinstance(value, str):
        try:
            value = _dt.datetime.fromisoformat(value.replace("Z", "+00:00"))
        except ValueError:
            return value
    if value.tzinfo is not None:
        value = value.astimezone(_dt.timezone.utc).replace(tzinfo=None)
    tz = tu.validate_tz(tz)
    local = tu.utc_to_local(value, tz)
    return f"{format_date(local, loc, 'full')}, {local:%H:%M} {tu.tz_abbrev(value, tz)}"


@pass_context
def jinja_status_label(context, status: Optional[str]) -> str:
    return status_label(status, context.get("locale"))


def register(env) -> None:
    """Register the i18n globals on a Jinja environment."""
    env.globals["t"] = jinja_t
    env.globals["status_label"] = jinja_status_label
    env.filters["ldt"] = jinja_ldt
    env.globals["i18n_catalog"] = catalog
    env.globals["locale_switcher_locales"] = SUPPORTED_LOCALES
    env.globals["supported_locales"] = SUPPORTED_LOCALES
